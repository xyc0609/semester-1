# Work out the answers to the three maths problems:

# 1: (4 x 8) x 6
answer1 = (4 * 8) * 6
print(f"The answer is: {answer1:.3f}")


# 2: (2^3) / (8/3)
answer2 = (2 ** 3) / (8 / 3)
print(f"The answer is: {answer2:.3f}")


# 3: 27^2 x 19/4
answer3 = (27 ** 2) * (19 / 4)
print(f"The answer is: {answer3:.3f}")
